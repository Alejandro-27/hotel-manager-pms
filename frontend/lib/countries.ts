export const countryByCode: Record<string, Country> = Object.fromEntries(
  countries.map((country) => [country.code, country])
)

const dialPrefixes = [...new Set(countries.map((country) => country.dial).filter(Boolean))].sort(
  (a, b) => b.length - a.length
)

/** Sustituye el prefijo internacional existente por el del pais elegido. */
export function applyDialPrefix(phone: string, dial: string): string {
  const value = phone.trim()
  let rest = value
  if (value.startsWith('+')) {
    const match = dialPrefixes.find((prefix) => value.startsWith(prefix))
    rest = match ? value.slice(match.length).trim() : value.replace(/^\+\s*/, '')
  }
  if (!dial) return rest
  return `${dial} ${rest}`
}
